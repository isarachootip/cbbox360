import {
  BotAutoReplyRule,
  BusinessTemplatePreset,
  ConnectorConfig,
  MenuItemConfig,
  UserRole,
} from '../../types';

/** A role that a template granted on a menu (only recorded if the role was NOT already present). */
export interface MenuRoleGrant {
  menuId: string;
  role: UserRole;
}

/** Everything a template actually added, so reset can remove exactly that and nothing else. */
export interface TemplateAddedResources {
  connectorIds: string[];
  cannedResponseIds: string[];
  ruleIds: string[];
  menuGrants: MenuRoleGrant[];
}

export const EMPTY_ADDED_RESOURCES: TemplateAddedResources = {
  connectorIds: [],
  cannedResponseIds: [],
  ruleIds: [],
  menuGrants: [],
};

type PresetCanned = BusinessTemplatePreset['cannedResponses'][number];

export const selectNewConnectors = (
  current: ConnectorConfig[],
  preset: BusinessTemplatePreset
): ConnectorConfig[] => {
  const existingIds = new Set(current.map((c) => c.id));
  return preset.connectors.filter((c) => !existingIds.has(c.id));
};

export const selectNewCannedResponses = (
  existingShortcuts: string[],
  preset: BusinessTemplatePreset
): PresetCanned[] => {
  const existing = new Set(existingShortcuts.map((s) => s.toLowerCase()));
  return preset.cannedResponses.filter((c) => !existing.has(c.shortcut.toLowerCase()));
};

/** Template rule ids are namespaced as `${templateRuleId}-${stamp}-${index}`. */
export const buildRulesToAdd = (
  existingRules: BotAutoReplyRule[],
  preset: BusinessTemplatePreset,
  shortcutToId: Map<string, string>,
  stamp: number
): BotAutoReplyRule[] => {
  const existingNames = new Set(existingRules.map((r) => r.name));
  return preset.botRules
    .filter((r) => !existingNames.has(r.name))
    .map((r, index) => {
      const templateCanned = preset.cannedResponses.find((c) => c.id === r.cannedResponseId);
      const resolvedId = templateCanned
        ? shortcutToId.get(templateCanned.shortcut.toLowerCase()) ?? r.cannedResponseId
        : r.cannedResponseId;
      return {
        ...r,
        id: `${r.id}-${stamp}-${index}`,
        cannedResponseId: resolvedId,
        priority: existingRules.length + index + 1,
      };
    });
};

export const computeMenuGrants = (
  menus: MenuItemConfig[],
  menuIds: string[],
  roles: UserRole[]
): MenuRoleGrant[] =>
  menuIds.flatMap((menuId) => {
    const target = menus.find((m) => m.id === menuId);
    if (!target) return [];
    return roles
      .filter((role) => !target.allowedRoles.includes(role))
      .map((role) => ({ menuId, role }));
  });

export const applyMenuGrants = (menus: MenuItemConfig[], grants: MenuRoleGrant[]): MenuItemConfig[] =>
  menus.map((m) => {
    const added = grants.filter((g) => g.menuId === m.id).map((g) => g.role);
    if (added.length === 0) return m;
    return { ...m, allowedRoles: Array.from(new Set([...m.allowedRoles, ...added])) };
  });

export const revertMenuGrants = (menus: MenuItemConfig[], grants: MenuRoleGrant[]): MenuItemConfig[] =>
  menus.map((m) => {
    const toRemove = new Set(grants.filter((g) => g.menuId === m.id).map((g) => g.role));
    if (toRemove.size === 0) return m;
    return { ...m, allowedRoles: m.allowedRoles.filter((r) => !toRemove.has(r)) };
  });

/** Removes connectors that came from any template; user-configured connectors are never touched. */
export const removeTemplateConnectors = (
  current: ConnectorConfig[],
  templates: BusinessTemplatePreset[],
  trackedIds: string[]
): ConnectorConfig[] => {
  const owned = new Set([...trackedIds, ...templates.flatMap((t) => t.connectors.map((c) => c.id))]);
  return current.filter((c) => !owned.has(c.id));
};

const TEMPLATE_RULE_SUFFIX = /^-\d+-\d+$/;

/** True only for ids generated by buildRulesToAdd (also matches rules created by Phase 1). */
const isTemplateRuleId = (ruleId: string, templates: BusinessTemplatePreset[]): boolean =>
  templates.some((t) =>
    t.botRules.some(
      (tr) => ruleId.startsWith(tr.id) && TEMPLATE_RULE_SUFFIX.test(ruleId.slice(tr.id.length))
    )
  );

export const removeTemplateRules = (
  rules: BotAutoReplyRule[],
  templates: BusinessTemplatePreset[],
  trackedIds: string[]
): BotAutoReplyRule[] => {
  const tracked = new Set(trackedIds);
  return rules.filter((r) => !tracked.has(r.id) && !isTemplateRuleId(r.id, templates));
};

const uniq = (values: string[]): string[] => Array.from(new Set(values));

export const mergeAddedResources = (
  a: TemplateAddedResources,
  b: TemplateAddedResources
): TemplateAddedResources => {
  const grantKey = (g: MenuRoleGrant) => `${g.menuId}::${g.role}`;
  const grants = new Map([...a.menuGrants, ...b.menuGrants].map((g) => [grantKey(g), g]));
  return {
    connectorIds: uniq([...a.connectorIds, ...b.connectorIds]),
    cannedResponseIds: uniq([...a.cannedResponseIds, ...b.cannedResponseIds]),
    ruleIds: uniq([...a.ruleIds, ...b.ruleIds]),
    menuGrants: Array.from(grants.values()),
  };
};
